interface ExportMessage {
  role: "user" | "assistant";
  content: string;
}

const ERROR_PATTERNS = [
  /cannot read.*\.(png|jpg|jpeg|gif|bmp|webp)/i,
  /does not support image/i,
  /this model does not support/i,
  /image input is not supported/i,
  /I can only analyze structured data/i,
  /\bERROR:\s*\w+/,
];

function isErrorMessage(msg: ExportMessage): boolean {
  if (msg.role !== "assistant") return false;
  return ERROR_PATTERNS.some(p => p.test(msg.content));
}

export function exportAsCSV(messages: ExportMessage[], martName: string) {
  const rows = [["Role", "Content", "Timestamp"]];
  const filtered = messages.filter(m => !isErrorMessage(m));
  if (filtered.length === 0) {
    rows.push(["System", '"No exportable content available. Only data-driven analysis results are exported."', new Date().toISOString()]);
  } else {
    filtered.forEach((m) => {
      rows.push([m.role === "user" ? "You" : "AI Assistant", `"${m.content.replace(/"/g, '""')}"`, new Date().toISOString()]);
    });
  }
  const csv = rows.map((r) => r.join(",")).join("\n");
  downloadFile(csv, `${martName}-chat-export.csv`, "text/csv");
}

export function exportAsPDF(messages: ExportMessage[], martName: string) {
  const filtered = messages.filter(m => !isErrorMessage(m));
  const skipCount = messages.length - filtered.length;

  const html = `
<!DOCTYPE html>
<html>
<head>
  <title>XYZ Bank Data Insight Agent - ${martName} Chat Export</title>
  <style>
    * { margin: 0; padding: 0; box-sizing: border-box; }
    body { font-family: Arial, sans-serif; padding: 40px; color: #1a1a1a; line-height: 1.6; }
    .header { border-bottom: 3px solid #12304a; padding-bottom: 16px; margin-bottom: 24px; }
    .header h1 { font-size: 22px; color: #12304a; }
    .header p { font-size: 12px; color: #666; margin-top: 4px; }
    .message { margin-bottom: 20px; page-break-inside: avoid; }
    .role { font-size: 11px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.05em; margin-bottom: 4px; }
    .role.user { color: #12304a; }
    .role.assistant { color: #0f766e; }
    .content { background: #f8f8f8; border-radius: 8px; padding: 12px 16px; font-size: 13px; white-space: pre-wrap; }
    .content.user { background: #eaf0f6; border-left: 3px solid #12304a; }
    .content.assistant { background: #e8f5f3; border-left: 3px solid #0f766e; }
    .footer { margin-top: 32px; padding-top: 16px; border-top: 1px solid #ddd; font-size: 11px; color: #999; text-align: center; }
    .note { background: #fef3cd; border: 1px solid #ffc107; border-radius: 8px; padding: 10px 16px; margin-bottom: 20px; font-size: 12px; color: #856404; }
    @media print { body { padding: 20px; } }
  </style>
</head>
<body>
  <div class="header">
    <h1>XYZ Bank Data Insight Agent — Chat Export</h1>
    <p>Data Mart: ${martName} &nbsp;|&nbsp; Exported: ${new Date().toLocaleString()}</p>
  </div>
  ${skipCount > 0 ? `<div class="note">${skipCount} system message(s) were omitted from this export. Only data-driven analysis is included.</div>` : ""}
  ${filtered.length > 0
    ? filtered
      .map(
        (m) => `
  <div class="message">
    <div class="role ${m.role}">${m.role === "user" ? "You" : "AI Assistant"}</div>
    <div class="content ${m.role}">${escapeHtml(m.content)}</div>
  </div>`
      )
      .join("")
    : '<div class="message"><div class="content" style="background: #fef3cd; border-left: 3px solid #ffc107;">No exportable content available. Only data-driven analysis results are exported.</div></div>'
  }
  <div class="footer">Generated by XYZ Bank Data Insight Agent</div>
</body>
</html>`;

  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const win = window.open(url, "_blank");
  if (win) {
    win.onload = () => {
      win.print();
      URL.revokeObjectURL(url);
    };
  } else {
    downloadFile(html, `${martName}-chat-export.html`, "text/html");
  }
}

function escapeHtml(text: string) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\n/g, "<br>");
}

function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
